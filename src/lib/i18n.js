export const DICTS = { en, he };

export function detectLang() {
  const langs = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || [];
  return langs.some((l) => /^(he|iw)\b/i.test(l || '')) ? 'he' : 'en';
}

/** A locale tag Intl accepts (device tags like "en-US@posix" would throw). */
export function safeLocale(lang) {
  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  const cands = lang === 'he' ? ['he-IL', 'he'] : [nav.split(/[@_]/)[0], 'en'];
  for (const c of cands) {
    if (lang !== 'he' && !/^en\b/i.test(c)) continue;
    try {
      new Intl.DateTimeFormat(c);
      return c;
    } catch {
      /* try next */
    }
  }
  return 'en';
}

export function makeT(lang) {
  const dict = DICTS[lang] || en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Display title: user text wins, else a translated default. On a Minimum Day the tiny version is shown. */
export const itemTitle = (t, item, minimum = false) => {
  if (minimum) {
    if (item.mini) return item.mini;
    if (item.key && !item.title) return t(`${item.key}.mini`);
  }
  return item.title || t(item.key);
};
